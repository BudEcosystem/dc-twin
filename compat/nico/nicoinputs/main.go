// Command nicoinputs turns what the twin hands a site's lifecycle manager into the files NICo's
// operator tooling loads:
//
//   - nico-site.toml: the BMC network's per-rack segments as nico-api `[networks.*]` underlay
//     sections, and a `[rack_profiles.*]` section for each NVL rack format;
//   - expected-{machines,power-shelves,switches,racks,rack-groups}.json: the twin's
//     stack-inputs/expected-machines.json in the shapes NICo's admin CLI `replace-all` reads.
//
// It reads the estate only for what an operator knows from the floor plan and the asset system:
// which device is a host, a power shelf, a switch tray or a DPU, and which rack segment the relay
// selects (dhcp.PlanSegments, the function the twin relay's link selection uses). Credentials,
// BMC MACs, serials and a switch tray's NVOS management MACs (nvosMACs, D46) come from
// expected-machines.json.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/BudEcosystem/dc-twin/internal/adapter/dhcp"
	"github.com/BudEcosystem/dc-twin/internal/compile"
	"github.com/BudEcosystem/dc-twin/internal/model"
	"github.com/BudEcosystem/dc-twin/internal/twin"
)

// nvlFormat matches a rack-scale NVLink rack format's name: gb300-nvl72, gb200-nvl36x2.
var nvlFormat = regexp.MustCompile(`^(gb[0-9]+)-nvl([0-9]+)`)

type label struct {
	Key   string `json:"key"`
	Value string `json:"value"`
}

type metadata struct {
	Name        string  `json:"name"`
	Description string  `json:"description"`
	Labels      []label `json:"labels"`
}

func main() {
	estate := flag.String("estate", "", "estate file")
	expected := flag.String("expected", "", "the twin's stack-inputs/expected-machines.json")
	out := flag.String("out", ".", "output directory")
	reserve := flag.Int("reserve-first", 10, "addresses kept back at the start of each segment (the twin reserves .2-.9)")
	flag.Parse()
	if *estate == "" || *expected == "" {
		fmt.Fprintln(os.Stderr, "usage: nicoinputs -estate <estate.yaml> -expected <expected-machines.json> -out <dir>")
		os.Exit(2)
	}
	if err := run(*estate, *expected, *out, *reserve); err != nil {
		fmt.Fprintln(os.Stderr, "nicoinputs:", err)
		os.Exit(1)
	}
}

func run(estatePath, expectedPath, out string, reserve int) error {
	reg, err := compile.Registry()
	if err != nil {
		return err
	}
	est, _, err := compile.LoadEstate(estatePath)
	if err != nil {
		return err
	}
	res, err := compile.Compile(est, reg, compile.Options{HostArch: compile.HostArch()})
	if err != nil {
		return err
	}
	m := res.Model

	// The BMC network's segments: one underlay segment per rack, named after the rack.
	var toml strings.Builder
	toml.WriteString("# Generated by compat/nico/nicoinputs from the estate: one NICo underlay segment per twin\n")
	toml.WriteString("# relay segment of the BMC (management) network. The twin relay's RFC 3527 link selection\n")
	toml.WriteString("# names the gateway, and NICo selects the segment whose prefix contains it.\n")
	// A provisioning network whose DHCP is the stack's is where the hosts' boot NICs lease: one
	// NICo HostInband (`hostinband`) segment per rack, the segment type NICo puts a zero-DPU host's NICs on
	// (an underlay segment is for BMCs; admin for hosts behind DPUs).
	var segs []string
	for _, s := range dhcp.PlanSegments(m) {
		n := m.Networks[s.Network]
		if n == nil || !s.Prefix.IsValid() {
			continue
		}
		kind := ""
		switch {
		case n.Role == "management":
			kind = "underlay"
		case n.Role == "provisioning" && n.DHCP == "stack":
			kind = "hostinband" // NICo's configuration spells HostInband so (cfg: admin, underlay, hostinband)
		default:
			continue
		}
		rack := m.RackBy[s.Rack]
		name := fmt.Sprintf("%s-%s", s.Network, rack.Name)
		segs = append(segs, fmt.Sprintf("%s %s %s gw %s", name, kind, s.Prefix, s.Gateway))
		fmt.Fprintf(&toml, "\n[networks.%s]\ntype = \"%s\"\nprefix = \"%s\"\ngateway = \"%s\"\nmtu = 1500\nreserve_first = %d\n",
			name, kind, s.Prefix, s.Gateway, reserve)
	}
	if len(segs) == 0 {
		return fmt.Errorf("the estate has no DHCP management network with an IPv4 CIDR")
	}

	b, err := os.ReadFile(expectedPath)
	if err != nil {
		return err
	}
	var list []twin.ExpectedMachine
	if err := json.Unmarshal(b, &list); err != nil {
		return fmt.Errorf("%s: %w", expectedPath, err)
	}
	byPath := map[string]twin.ExpectedMachine{}
	for _, e := range list {
		byPath[e.Path] = e
	}

	var machines, shelves, switches []map[string]any
	racks := map[string]bool{}
	rackPaths := map[string]string{}
	// members of each rack, for NICo's expected rack group: NICo derives an expected rack's
	// profile from a group that lists its Compute, Switch and PowerShelf members.
	members := map[string][]map[string]any{}
	kinds := map[string]map[string]bool{}
	member := func(rack, kind string, d *model.Device, serial string) {
		mf := ""
		if d.Profile != nil && d.Profile.Spec.Identity != nil {
			mf = d.Profile.Spec.Identity.Manufacturer
		}
		members[rack] = append(members[rack], map[string]any{"type": kind, "manufacturer": mf, "id": serial})
		if kinds[rack] == nil {
			kinds[rack] = map[string]bool{}
		}
		kinds[rack][kind] = true
	}
	skipped := map[string]int{}
	var noNVOS, zeroDPU []string
	paths := make([]string, 0, len(list))
	for _, e := range list {
		paths = append(paths, e.Path)
	}
	sort.Strings(paths)
	for _, p := range paths {
		e := byPath[p]
		d := m.DeviceBy[p]
		if d == nil {
			return fmt.Errorf("%s is in expected-machines.json but not in the estate", p)
		}
		meta := metadata{Name: strings.TrimPrefix(p, d.RackOf().Path+"/"), Description: "dc-twin " + p,
			Labels: []label{{Key: "dc-twin.path", Value: p}}}
		meta.Name = e.Rack + "-" + strings.ReplaceAll(meta.Name, "/", "-")
		switch d.Class {
		case "compute-tray", "server":
			member(e.Rack, "Compute", d, e.Serial)
			em := map[string]any{
				"bmc_mac_address": e.BMCMAC, "bmc_username": e.User, "bmc_password": e.Password,
				"chassis_serial_number": e.Serial, "rack_id": e.Rack, "metadata": meta,
			}
			if nic := bootNIC(m, d); nic != nil {
				// A host that boots for real (vm fidelity, os: stack) is ingested as a zero-DPU
				// host: its BlueField is a model device with no DPU OS for NICo to provision, so
				// the operator declares it ignored, and declares the host's boot NIC (the
				// provisioning port it network-boots from) primary on a HostInband segment.
				// NICo's own simulator registers zero-DPU hosts the same way (machine-a-tron).
				em["dpu_policy"] = "ignore"
				em["interfaces"] = []map[string]any{{"mac_address": nic.MAC, "primary": true, "network_segment_type": 3}}
				zeroDPU = append(zeroDPU, fmt.Sprintf("%s (boot NIC %s %s)", p, nic.Ref, nic.MAC))
			}
			machines = append(machines, em)
		case "power-shelf":
			member(e.Rack, "PowerShelf", d, e.Serial)
			shelves = append(shelves, map[string]any{
				"bmc_mac_address": e.BMCMAC, "bmc_username": e.User, "bmc_password": e.Password,
				"shelf_serial_number": e.Serial, "rack_id": e.Rack, "metadata": meta,
			})
		case "switch-tray":
			member(e.Rack, "Switch", d, e.Serial)
			sw := map[string]any{
				"bmc_mac_address": e.BMCMAC, "bmc_username": e.User, "bmc_password": e.Password,
				"switch_serial_number": e.Serial, "rack_id": e.Rack, "metadata": meta,
			}
			// The switch OS (NVOS) management port's MACs, as the site's inventory (the twin's
			// expected machines) lists them: NICo will not create a switch without one, and finds
			// the switch's NVOS among the interfaces that DHCP by them.
			if len(e.NVOSMACs) > 0 {
				sw["nvos_mac_addresses"] = e.NVOSMACs
				// NVOS's users are the tray BMC's accounts in the twin (the nvue adapter), so the
				// switch OS's credentials are the BMC's factory ones, as for a tray fresh from the
				// factory whose NVOS admin was set to its BMC's.
				sw["nvos_username"], sw["nvos_password"] = e.User, e.Password
			} else {
				noNVOS = append(noNVOS, p)
			}
			switches = append(switches, sw)
		default:
			// DPUs are found by NICo from their own BMC on the underlay and paired with their
			// host; PDUs and appliances are not something NICo ingests.
			skipped[d.Class]++
			continue
		}
		racks[e.Rack] = true
		rackPaths[e.Rack] = d.RackOf().Path
	}
	// NICo's expected racks are rack-scale systems, declared through an expected rack group whose
	// topology and member manufacturers name a rack profile NICo's configuration must hold. A twin
	// rack of format <vendor>/gbNNN-nvlMM is declared with topology gbNNN_nvlMMr1_c2g4 (NICo's
	// RackHardwareTopology names) and a profile is written for it; rows of OEM servers carry a
	// rack id on their expected machines and no expected rack.
	var rackList []map[string]any
	groupRacks := map[string][]map[string]any{}
	var profiles strings.Builder
	profiled := map[string]bool{}
	for _, r := range sortedKeys(racks) {
		rk := m.RackBy[rackPaths[r]]
		mm := nvlFormat.FindStringSubmatch(path.Base(rk.FormatName))
		if mm == nil || !kinds[r]["Compute"] || !kinds[r]["Switch"] {
			continue
		}
		topology := fmt.Sprintf("%s_nvl%sr1_c2g4", mm[1], mm[2])
		rackList = append(rackList, map[string]any{"rack_id": r, "metadata": metadata{Name: r, Description: "dc-twin rack " + r, Labels: []label{}}})
		groupRacks[topology] = append(groupRacks[topology], map[string]any{"rack_id": r, "members": members[r]})
		profile := strings.ToUpper(topology) + "_NVIDIA"
		if profiled[profile] {
			continue
		}
		profiled[profile] = true
		count := map[string]int{}
		vendor := map[string]string{}
		for _, mb := range members[r] {
			k := mb["type"].(string)
			count[k]++
			vendor[k] = mb["manufacturer"].(string)
		}
		fmt.Fprintf(&profiles, "\n[rack_profiles.%s]\nproduct_family = %q\nrack_hardware_topology = %q\n", profile, mm[1], topology+"_topology")
		for _, c := range [][2]string{{"compute", "Compute"}, {"switch", "Switch"}, {"power_shelf", "PowerShelf"}} {
			fmt.Fprintf(&profiles, "[rack_profiles.%s.rack_capabilities.%s]\ncount = %d\nvendor = %q\n", profile, c[0], count[c[1]], vendor[c[1]])
		}
	}
	groups := []map[string]any{}
	for _, t := range sortedKeys(groupRacks) {
		groups = append(groups, map[string]any{"rack_group_id": m.Name + "-" + t, "protocol": "dc-twin", "topology": t,
			"racks": groupRacks[t], "metadata": metadata{Name: m.Name + " " + t, Description: "dc-twin estate " + m.Name, Labels: []label{}}})
	}
	if profiles.Len() > 0 {
		toml.WriteString("\n# Rack profiles for the expected racks (see expected-rack-groups.json).\n")
		toml.WriteString(profiles.String())
	}

	if err := os.MkdirAll(out, 0o700); err != nil {
		return err
	}
	files := map[string]any{
		"expected-machines.json":      map[string]any{"expected_machines": machines},
		"expected-power-shelves.json": map[string]any{"expected_power_shelves": shelves},
		"expected-switches.json":      map[string]any{"expected_switches": switches},
		"expected-racks.json":         map[string]any{"expected_racks": rackList},
		"expected-rack-groups.json":   map[string]any{"expected_rack_groups": groups},
	}
	for name, v := range files {
		b, _ := json.MarshalIndent(v, "", "  ")
		if err := os.WriteFile(filepath.Join(out, name), b, 0o600); err != nil {
			return err
		}
	}
	if err := os.WriteFile(filepath.Join(out, "nico-site.toml"), []byte(toml.String()), 0o644); err != nil {
		return err
	}
	var sk []string
	for _, c := range sortedKeys(skipped) {
		sk = append(sk, fmt.Sprintf("%d %s", skipped[c], c))
	}
	fmt.Printf("segments: %s\n", strings.Join(segs, "; "))
	fmt.Printf("expected: %d machines, %d power shelves, %d switches, %d racks; not NICo expected entities: %s\n",
		len(machines), len(shelves), len(switches), len(rackList), strings.Join(sk, ", "))
	if len(zeroDPU) > 0 {
		fmt.Printf("zero-DPU hosts: %s\n", strings.Join(zeroDPU, ", "))
	}
	if len(noNVOS) > 0 {
		fmt.Fprintf(os.Stderr, "nicoinputs: %d switch trays have no nvosMACs in %s (a twin older than D46?); NICo will hold them in error: %s\n",
			len(noNVOS), expectedPath, strings.Join(noNVOS, ", "))
	}
	return nil
}

// bootNIC is the port a vm host with the stack's OS network-boots from: its first Ethernet port
// (or a sub-device's at model fidelity, as the host sees a BlueField's ports) on a provisioning
// network whose DHCP is the stack's. Other hosts are not booted by the stack, and have none.
func bootNIC(m *model.Model, d *model.Device) *model.Port {
	if d.Fidelity != "vm" || d.OS != "stack" {
		return nil
	}
	ports := append([]*model.Port{}, d.Ports...)
	for _, ch := range d.Children {
		if ch.Fidelity != "vm" {
			ports = append(ports, ch.Ports...)
		}
	}
	for _, p := range ports {
		n := m.Networks[p.Network]
		if p.Kind == "ethernet" && p.MAC != "" && p.Role == "provisioning" && n != nil && n.DHCP == "stack" {
			return p
		}
	}
	return nil
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
